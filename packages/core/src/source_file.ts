/**
 * This module provides the {@linkcode SourceFile} class, an abstraction over a
 * single source file in a particular project. Its primary purpose is to house
 * the source code of a text-based file that is being linted.
 *
 * ### Source Code Representation
 *
 * The source code is stored internally as a buffer of binary data (raw bytes),
 * which is then decoded into a string using the appropriate text encoding. The
 * public API of the class exposes the source code primarily as a string, for
 * ease of use and manipulation, while also allowing access to the raw buffer
 * for more advanced use cases. This is done to maximize performance during
 * transport and manipulation operations, without sacrificing usability.
 *
 * ### Diagnostics
 *
 * The class also provides a mechanism for storing and managing diagnostic
 * messages that are generated during the linting process. These messages are
 * stored as instances of the {@linkcode Diagnostic} class, which encapsulates
 * information about the location, severity, and message of the diagnostic.
 *
 * #### Snapshotting and "Dirty" State
 *
 * When the linter is run on a source file, any diagnostics that are generated
 * will be stored in the `diagnostics` property of the `SourceFile` instance.
 * The contents of the file at the time of linting are internally snapshotted
 * and associated with the diagnostics, which allows the SourceFile to signal
 * that it has been modified in the meantime, indicating that the diagnostics
 * may no longer be valid.
 *
 * ### Manipulation
 *
 * Instances of the `SourceFile` class also implement several utility methods
 * for manipulating the source code, either as a whole or in parts (e.g., by
 * extracting a range of lines or characters).
 *
 * #### Lint Fixes
 *
 * The class also provides methods for applying fix suggestions to the source
 * code, such as those generated by the {@link Linter} for supported rules.
 *
 * ```ts
 * import { SourceFile } from "jsr:@nick/lint";
 * ```
 *
 * @see {@linkcode LintFix} and {@linkcode LintFixChange} for more info.
 *
 * @module source-file
 */
